#!/usr/bin/env node
// Copies each capability's contract.ts into packages/sdk/src/contracts/ so
// the SDK package is self-contained when installed from npm — a published
// tarball only ever contains packages/sdk's own directory, so the SDK's
// source can't reach ../../../capabilities/<name>/contract.ts the way it
// can inside this monorepo. capabilities/<name>/contract.ts stays the
// canonical source (root AGENTS.md rule 1); this only ever copies it.
//
// Runs automatically via the "prepare"/"prepublishOnly" scripts — never
// edit packages/sdk/src/contracts/*.ts by hand, it's overwritten every run.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sdkRoot = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const chainRoot = path.resolve(sdkRoot, "../..");
const capabilitiesDir = path.join(chainRoot, "capabilities");
const outDir = path.join(sdkRoot, "src/contracts");

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const header = "// GENERATED by scripts/sync-contracts.mjs — do not edit.\n" +
  "// Source of truth: capabilities/<name>/contract.ts (see root AGENTS.md).\n\n";

for (const name of fs.readdirSync(capabilitiesDir)) {
  const contractPath = path.join(capabilitiesDir, name, "contract.ts");
  if (!fs.existsSync(contractPath)) continue;
  const content = fs.readFileSync(contractPath, "utf8");
  fs.writeFileSync(path.join(outDir, `${name}.ts`), header + content);
  console.log(`sync-contracts: capabilities/${name}/contract.ts -> packages/sdk/src/contracts/${name}.ts`);
}
